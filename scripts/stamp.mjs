/* Writes assets/js/build.js with the current local time, to the minute.
   Run via `npm run build` so the header stamp can never drift out of date. */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "assets", "js", "build.js");

const d = new Date();
const p = (n) => String(n).padStart(2, "0");
const stamp = `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;

writeFileSync(
  out,
  `/* Build stamp — regenerated by \`npm run build\`. */\nwindow.RK_BUILD = "${stamp}";\n`
);

console.log(`build stamp: ${stamp}`);
